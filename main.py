"""
Точка входа в приложение "Визуальный редактор диаграмм"

Этот скрипт:
1. Инициализирует базу данных
2. Создает экземпляр QApplication
3. Создает и отображает главное окно приложения
4. Запускает цикл обработки событий Qt

Структура запуска:
- Инициализация БД (создание таблиц при первом запуске)
- Создание GUI приложения
- Запуск основного цикла обработки событий
"""

import sys
from PyQt6.QtWidgets import QApplication
from database import initialize_database  # Импорт функции инициализации БД
from ui.main_window import MainWindow  # Импорт главного окна приложения

def main() -> None:
    """
    Основная функция запуска приложения
    
    Выполняет:
    1. Инициализацию базы данных
    2. Создание Qt-приложения
    3. Создание и отображение главного окна
    4. Запуск цикла обработки событий
    """
    # Инициализация базы данных (создание таблиц при необходимости)
    initialize_database()
    
    # Создание экземпляра QApplication (обязательно для любого Qt-приложения)
    app = QApplication(sys.argv)
    
    # Создание и настройка главного окна приложения
    main_window = MainWindow()
    main_window.setWindowTitle("Визуальный редактор диаграмм")
    main_window.resize(1000, 700)  # Начальный размер окна
    
    # Отображение главного окна
    main_window.show()
    
    # Запуск основного цикла обработки событий Qt
    # Возвращает код завершения приложения при выходе
    sys.exit(app.exec())

# Точка входа при запуске скрипта напрямую
if __name__ == '__main__':
    main()